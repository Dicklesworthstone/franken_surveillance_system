#![forbid(unsafe_code)]
//! Constrained-Baseline H.264 pixel decode, scalar reference implementation.
//!
//! NAL units enter, reconstructed 8-bit 4:2:0 pictures leave, with every
//! stage bounded, deterministic, and typed-error on hostile input. Parameter
//! sets are first admitted by `fss-packet`'s AVC custody parser (which owns
//! the admission decision and refuses what it cannot bound); this crate then
//! reads the decode-relevant fields that custody deliberately leaves inside
//! the exact original NAL bytes.
//!
//! Stage map, in decode order:
//! 1. [`rbsp`] — NAL header, emulation-prevention removal, trailing bits.
//! 2. [`bits`] — bounds-checked bit reader with ue/se/te mappings.
//! 3. [`params`] / [`slice`] — SPS/PPS decode fields and slice headers.
//! 4. [`cavlc`] / [`residual`] — CAVLC residual blocks (clause 9.2).
//! 5. `macroblock` — I_NxN, I_16x16, I_PCM, P_L0 partitions, P_Skip.
//! 6. [`intra`] / [`transform`] / `inter` — prediction, dequantisation,
//!    inverse transforms, quarter-pel luma / eighth-pel chroma interpolation.
//! 7. `deblock` — the in-loop deblocking filter (clause 8.7).
//! 8. [`decoder`] — the streaming [`Decoder`], reference list, sliding-window
//!    marking, output in decode order.
//!
//! Admitted tool set: CAVLC, I and P slices, frame pictures, 8-bit 4:2:0,
//! flat scaling, one slice group, slices in raster order, sliding-window
//! reference marking, no reference-list modification, no weighted
//! prediction, POC type 0 without reordering or POC type 2. Everything else
//! is refused with [`DecodeError::Unsupported`] naming the feature.
//!
//! Correctness is established differentially: tests compare every decoded
//! frame bit-exactly against digests produced offline by the sealed FFmpeg
//! laboratory oracle (never invoked at runtime or by tests).
