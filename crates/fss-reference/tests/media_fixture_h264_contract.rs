#[test]
fn test_media_fixture_h264_fua_contiguity_and_markers() -> Result<(), Box<dyn Error>> {
    let h264_params = H264FixtureParams::default();
    let annexb = generate_h264_annexb(&h264_params)?;
    let rtp_params = RtpdumpParams::default();
    let clean = generate_rtpdump_clean(&annexb, &rtp_params)?;

    let mut offset = RTPDUMP_MAGIC_HEADER.len() + RD_HDR_LEN;
    let mut rtp_packets = Vec::new();
    while offset + RD_PKT_HDR_LEN <= clean.bytes.len() {
        let length = u16::from_be_bytes([clean.bytes[offset], clean.bytes[offset + 1]]) as usize;
        let rtp_bytes = &clean.bytes[offset + RD_PKT_HDR_LEN..offset + length];
        rtp_packets.push(rtp_bytes);
        offset += length;
    }

    assert_eq!(rtp_packets.len(), clean.packets.len());

    let mut found_fua = false;
    let mut in_fua = false;
    let mut fua_inner_type = 0u8;
    for (idx, rtp_wire) in rtp_packets.iter().enumerate() {
        assert!(rtp_wire.len() >= 12);
        let m_bit = (rtp_wire[1] & 0x80) != 0;
        let payload = &rtp_wire[12..];
        assert!(!payload.is_empty());

        let nal_header = payload[0];
        let nal_type = nal_header & 0x1f;

        if nal_type == 28 {
            found_fua = true;
            assert!(payload.len() >= 2);
            let fu_header = payload[1];
            let s_bit = (fu_header & 0x80) != 0;
            let e_bit = (fu_header & 0x40) != 0;
            let r_bit = (fu_header & 0x20) != 0;

            assert!(!r_bit, "pkt {idx}: FU-A reserved bit must be 0");
            assert!(
                !(s_bit && e_bit),
                "pkt {idx}: FU-A S and E cannot both be set"
            );
            let inner_type = fu_header & 0x1f;
            assert!(
                (1..=23).contains(&inner_type),
                "pkt {idx}: FU-A inner type {inner_type} must be valid"
            );

            // F2 / M1 guard: assert S on first fragment, E on last, and fragment contiguity
            if !in_fua {
                assert!(
                    s_bit,
                    "pkt {idx}: first FU-A fragment must have S bit set (M1 guard)"
                );
                assert!(
                    !e_bit,
                    "pkt {idx}: first FU-A fragment must not have E bit set"
                );
                in_fua = true;
                fua_inner_type = inner_type;
            } else {
                assert!(
                    !s_bit,
                    "pkt {idx}: continuation FU-A fragment must not have S bit set (M1 guard)"
                );
                assert_eq!(
                    inner_type, fua_inner_type,
                    "pkt {idx}: FU-A continuation fragment inner type {inner_type} differs from start {fua_inner_type}"
                );
                if e_bit {
                    in_fua = false;
                }
            }

            if m_bit {
                assert!(
                    e_bit,
                    "pkt {idx}: RTP marker bit on FU-A packet may only be set if FU-A E bit is set"
                );
            }
        } else {
            assert!(
                !in_fua,
                "pkt {idx}: non-FU-A packet while FU-A sequence is incomplete"
            );
        }
    }
    assert!(!in_fua, "FU-A sequence did not terminate with an E bit");
    assert!(found_fua, "clean.rtp must exercise FU-A fragmentation");

    println!(
        r#"CAPLOG {{"step": "media_fixture_h264_fua_contiguity_and_markers", "verdict": "pass"}}"#
    );
    Ok(())
}

#[test]
fn test_media_fixture_h264_non_default_params_nal_equivalence() -> Result<(), Box<dyn Error>> {
    let test_configs = [(6, 2), (5, 1), (7, 3)];

    for (frame_count, gop_size) in test_configs {
        let hp = H264FixtureParams {
            seed: 9999,
            frame_count,
            gop_size,
            include_aud: true,
            include_sei: true,
            two_slice_au: true,
            force_emulation_prevention: true,
            trailing_zeros: 1,
        };
        let annexb = generate_h264_annexb(&hp)?;
        let rp = RtpdumpParams::default();
        let clean = generate_rtpdump_clean(&annexb, &rp)?;

        let (recs, trunc) = parse_rtpdump_records(&clean.bytes);
        assert!(!trunc);

        let key = StreamKey {
            ingress: 1,
            generation: 1,
            ssrc: rp.ssrc,
        };
        let mut tracker = SequenceTracker::new(key, rp.payload_type).map_err(|e| format!("{e}"))?;
        let mut depack = H264Depacketizer::new(
            key,
            rp.payload_type,
            H264Mode::NonInterleaved,
            H264Limits::default(),
        )
        .map_err(|e| format!("{e}"))?;

        let mut delivered = Vec::new();
        for (idx, rec) in recs.iter().enumerate() {
            let pkt = RtpPacket::parse(rec, PacketLimits::default())?;
            let obs = tracker.observe(key, pkt).map_err(|e| format!("{e}"))?;
            if let Some(ext) = obs.extended_sequence {
                let out = depack
                    .push(key, ext, pkt, idx as u64 * 1_000_000)
                    .map_err(|e| format!("{e}"))?;
                for n in &out.nals {
                    delivered.push(n.bytes().to_vec());
                }
            }
        }

        let annex: Vec<Vec<u8>> = annexb.nals.iter().map(|n| n.wire_bytes.clone()).collect();
        assert_eq!(
            delivered, annex,
            "exact NAL equivalence failed for frame_count={frame_count}, gop_size={gop_size}"
        );
    }

    println!(
        r#"CAPLOG {{"step": "media_fixture_h264_non_default_params_nal_equivalence", "verdict": "pass"}}"#
    );
    Ok(())
}

#[test]
fn test_media_fixture_h264_tamper_detection() -> Result<(), Box<dyn Error>> {
    let root = repo_root()?;
    let h264_man_path = root.join("tests/fixtures/media/h264/fixture_manifest.json");
    let h264_manifest = fs::read_to_string(&h264_man_path)?;
    let h264_file = root.join("tests/fixtures/media/h264/clean.264");
    let clean_264 = fs::read(&h264_file)?;

    // Untampered Annex-B fixture verification succeeds
    verify_fixture_manifest(&h264_manifest, "clean.264", &clean_264)?;

    // Mutating a single byte in Annex-B stream causes typed DigestMismatch
    let mut tampered_bytes = clean_264;
    assert!(!tampered_bytes.is_empty());
    tampered_bytes[10] ^= 0xff;
    let err_264 = verify_fixture_manifest(&h264_manifest, "clean.264", &tampered_bytes);
    assert!(
        matches!(err_264, Err(MediaFixtureError::DigestMismatch { .. })),
        "tampered Annex-B fixture must fail manifest check with typed DigestMismatch, got: {err_264:?}"
    );

    let rtp_man_path = root.join("tests/fixtures/media/rtp/fixture_manifest.json");
    let rtp_manifest = fs::read_to_string(&rtp_man_path)?;
    let rtp_file = root.join("tests/fixtures/media/rtp/clean.rtp");
    let clean_rtp = fs::read(&rtp_file)?;

    // Untampered RTP fixture verification succeeds
    verify_fixture_manifest(&rtp_manifest, "clean.rtp", &clean_rtp)?;

    // Mutating a single byte in clean.rtp causes typed DigestMismatch
    let mut tampered_rtp = clean_rtp;
    assert!(!tampered_rtp.is_empty());
    tampered_rtp[50] ^= 0x01;
    let err_rtp = verify_fixture_manifest(&rtp_manifest, "clean.rtp", &tampered_rtp);
    assert!(
        matches!(err_rtp, Err(MediaFixtureError::DigestMismatch { .. })),
        "tampered RTP fixture must fail manifest check with typed DigestMismatch, got: {err_rtp:?}"
    );

    println!(r#"CAPLOG {{"step": "media_fixture_h264_tamper_detection", "verdict": "pass"}}"#);
    Ok(())
}
