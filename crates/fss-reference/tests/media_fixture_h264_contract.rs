//! Acceptance criteria:
//! - cargo test -p fss-reference --test media_fixture_h264_contract passes
//! - regeneration identity for committed fixtures byte-for-byte against pinned hashes
//! - F2: asserts S on first FU-A fragment, E on last, and fragment contiguity (mutant M1 killer)
//! - F3: non-default params (gop_size < frame_count) exact NAL equivalence
//! - Tamper detection: mutating any fixture byte fails verification

