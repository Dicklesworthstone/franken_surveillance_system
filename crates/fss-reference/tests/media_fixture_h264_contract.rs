fn repo_root() -> Result<PathBuf, Box<dyn Error>> {
    let p = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .map(PathBuf::from)
        .ok_or("cannot find repo root")?;
    Ok(p)
}

fn to_hex(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        use std::fmt::Write;
        let _ = write!(s, "{b:02x}");
    }
    s
}

fn parse_rtpdump_records(bytes: &[u8]) -> (Vec<Vec<u8>>, bool) {
    let mut o = match bytes.iter().position(|&b| b == b'\n') {
        Some(p) => p + 1 + 16,
        None => return (Vec::new(), true),
    };
    let mut out = Vec::new();
    while o < bytes.len() {
        if o + 8 > bytes.len() {
            return (out, true);
        }
        let len = usize::from(u16::from_be_bytes([bytes[o], bytes[o + 1]]));
        if o + len > bytes.len() || len < 8 {
            return (out, true);
        }
        out.push(bytes[o + 8..o + len].to_vec());
        o += len;
    }
    (out, false)
}

#[test]
fn test_media_fixture_h264_regeneration_identity() -> Result<(), Box<dyn Error>> {
    let h264_params = H264FixtureParams::default();
    let annexb = generate_h264_annexb(&h264_params)?;
    let rtp_params = RtpdumpParams::default();

    let clean = generate_rtpdump_clean(&annexb, &rtp_params)?;
    let loss = generate_rtpdump_loss(&annexb, &rtp_params)?;
    let reorder = generate_rtpdump_reorder(&annexb, &rtp_params)?;
    let duplicate = generate_rtpdump_duplicate(&annexb, &rtp_params)?;
    let ssrc_reset = generate_rtpdump_ssrc_reset(&annexb, &rtp_params)?;
    let truncated = generate_rtpdump_truncated_last_record(&annexb, &rtp_params)?;
    let large_gap = generate_rtpdump_large_gap(&annexb, &rtp_params)?;

    let root = repo_root()?;

    // Check clean.264
    let h264_file = root.join("tests/fixtures/media/h264/clean.264");
    assert!(h264_file.is_file(), "clean.264 must exist on disk");
    let on_disk_264 = fs::read(&h264_file)?;
    assert_eq!(
        on_disk_264, annexb.bytes,
        "clean.264 must match regenerated bytes"
    );
    let digest_264 = to_hex(&ContentDigest::sha256(&on_disk_264).bytes());
    assert_eq!(digest_264, PINNED_SHA256_H264_CLEAN);

    // Check all 7 RTP fixtures
    let rtp_fixtures: [(&str, &RtpdumpFixture, &str); 7] = [
        ("clean.rtp", &clean, PINNED_SHA256_RTP_CLEAN),
        ("loss.rtp", &loss, PINNED_SHA256_RTP_LOSS),
        ("reorder.rtp", &reorder, PINNED_SHA256_RTP_REORDER),
        ("duplicate.rtp", &duplicate, PINNED_SHA256_RTP_DUPLICATE),
        ("ssrc_reset.rtp", &ssrc_reset, PINNED_SHA256_RTP_SSRC_RESET),
        (
            "truncated_last_record.rtp",
            &truncated,
            PINNED_SHA256_RTP_TRUNCATED,
        ),
        ("large_gap.rtp", &large_gap, PINNED_SHA256_RTP_LARGE_GAP),
    ];

    for (fname, fix, pinned_sha) in rtp_fixtures {
        let rtp_path = root.join("tests/fixtures/media/rtp").join(fname);
        assert!(rtp_path.is_file(), "{fname} must exist on disk");
        let on_disk = fs::read(&rtp_path)?;
        assert_eq!(
            on_disk, fix.bytes,
            "committed {fname} must match regenerated bytes byte-for-byte"
        );
        let digest_on_disk = to_hex(&ContentDigest::sha256(&on_disk).bytes());
        assert_eq!(digest_on_disk, pinned_sha);
    }
    println!(r#"CAPLOG {{"step": "media_fixture_h264_regeneration_identity", "verdict": "pass"}}"#);
    Ok(())
}

